//! `gen-lut` — committed generator for `assets/luts/podcast_warm.cube`.
//!
//! The `podcast-warm.sflook` preset references `color/luts/podcast_warm.cube`
//! (the project-relative LUT path convention); the built-in copy of that LUT
//! lives in `assets/luts/` and is produced by this tool so the creative
//! intent stays in version-controlled code, not in a magic binary blob.
//!
//! Run: `cargo run -p gen-lut [-- <output.cube>]`
//! (default output: `<repo>/assets/luts/podcast_warm.cube`).
//!
//! # The look
//!
//! A warm podcast / talking-head LUT matching the preset's params
//! (exposure +0.1, temperature 5400 K, warm gain [1.03, 1.0, 0.97],
//! applied at 0.6 intensity in the preset). The creative transform, applied
//! per lattice node in the [0, 1] domain:
//!
//! 1. **Warm shadows lift** — amber lift (red strongest, then green, then
//!    blue) that fades quadratically toward white, so blacks sit warm
//!    without washing out highlights.
//! 2. **Mid warmth** — gentle red boost / blue cut peaking at midtones via
//!    a sine bump, plus a whisper of green for skin.
//! 3. **Slight saturation** — 6% chroma push around luma, neutrals stay
//!    neutral.
//!
//! White (1,1,1) maps to itself: the lift and warmth terms vanish at the top
//! of the domain, and saturation of a neutral is the identity.

use std::path::PathBuf;

/// Lattice size per axis (matches the engine's normalized 33³).
const SIZE: usize = 33;

/// Warm shadows lift per channel (red, green, blue): added as
/// `lift * (1 - c)^2` so the lift is strongest in the shadows and zero at
/// white. Amber balance: red lifted most.
const SHADOW_LIFT: [f32; 3] = [0.030, 0.018, 0.012];

/// Midtone warmth bump per channel: `c *= 1 + bump * sin(pi * c)`.
/// Red up, blue down, green nearly flat — the "warm podcast" feel.
const WARM_BUMP: [f32; 3] = [0.05, 0.008, -0.05];

/// Saturation multiplier around luma.
const SATURATION: f32 = 1.06;

/// Apply the creative transform to one RGB triple in [0, 1].
fn warm_grade(rgb: [f32; 3]) -> [f32; 3] {
    // 1. Warm shadows lift.
    let mut c = [0.0f32; 3];
    for i in 0..3 {
        let v = rgb[i];
        c[i] = v + SHADOW_LIFT[i] * (1.0 - v) * (1.0 - v);
    }
    // 2. Mid warmth (sine bump peaks at 0.5, vanishes at 0 and 1).
    for i in 0..3 {
        c[i] *= 1.0 + WARM_BUMP[i] * (std::f32::consts::PI * c[i].clamp(0.0, 1.0)).sin();
    }
    // 3. Slight saturation around luma.
    let luma = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
    for i in 0..3 {
        c[i] = luma + (c[i] - luma) * SATURATION;
        c[i] = c[i].clamp(0.0, 1.0);
    }
    c
}

/// Render the full `.cube` file text (red-fastest node order).
fn render_cube() -> String {
    let mut out = String::with_capacity(SIZE * SIZE * SIZE * 24 + 1024);
    out.push_str("TITLE \"Podcast Warm — built-in warm podcast LUT\"\n");
    out.push_str("# Generated by tools/gen-lut (StreamFlow Lite C8). Do not hand-edit;\n");
    out.push_str("# change the transform in src/main.rs and re-run `cargo run -p gen-lut`.\n");
    out.push_str("# Warm shadows lift (amber), gentle midtone warmth, +6% saturation.\n");
    out.push_str("# Matches podcast-warm.sflook (5400 K, warm gain, 0.6 LUT intensity).\n");
    out.push_str("LUT_3D_SIZE 33\n");
    out.push_str("DOMAIN_MIN 0.0 0.0 0.0\n");
    out.push_str("DOMAIN_MAX 1.0 1.0 1.0\n");
    // Red varies fastest, then green, then blue (standard .cube order).
    for b in 0..SIZE {
        for g in 0..SIZE {
            for r in 0..SIZE {
                let f = SIZE as f32 - 1.0;
                let graded = warm_grade([r as f32 / f, g as f32 / f, b as f32 / f]);
                out.push_str(&format!(
                    "{:.6} {:.6} {:.6}\n",
                    graded[0], graded[1], graded[2]
                ));
            }
        }
    }
    out
}

fn default_output() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../assets/luts/podcast_warm.cube")
}

fn main() {
    let output: PathBuf = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(default_output);
    let text = render_cube();
    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent).expect("create output dir");
    }
    std::fs::write(&output, text).expect("write .cube");
    println!("wrote {}", output.display());
}
